export function toAttachmentResultLabel(value?: string | null) {
  if (!value) return ''
  return ATTACHMENT_RESULT_LABEL_MAP[value as keyof typeof ATTACHMENT_RESULT_LABEL_MAP] ?? value
}

export function toAttachmentResultLabelKey(value?: string | null) {
  if (!value) return undefined
  if (value in ATTACHMENT_RESULT_LABEL_MAP) {
    return value as AttachmentResultLabelKey
  }

  return ATTACHMENT_RESULT_LABEL_TO_KEY_MAP[value as AttachmentResultLabelValue]
}

export function toAttachmentResultEmoji(value?: string | null) {
  const labelKey = toAttachmentResultLabelKey(value)
  if (!labelKey) return ''

  return ATTACHMENT_RESULT_EMOJI_MAP[labelKey] ?? ''
}
